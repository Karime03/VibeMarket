-- Perfil de cada usuario (1 a 1 con auth.users). Rol: comprador, vendedor o admin.
create table public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  role        text not null default 'buyer' check (role in ('buyer','vendor','admin')),
  name        text not null,
  email       text not null,
  phone       text,
  city        text,
  birth       date,
  interests   text[] not null default '{}',
  prefs       jsonb  not null default '{}'::jsonb,       -- preferencias de comunicación
  status      text not null default 'active' check (status in ('active','suspended')),
  brand_id    text,                                      -- FK se agrega después de crear brands
  created_at  timestamptz not null default now()
);

-- Marcas (vendedores). Datos públicos de la tienda.
create table public.brands (
  id          text primary key,                          -- slug, ej. 'hilo-rojo'
  owner_id    uuid not null references public.profiles(id) on delete cascade,
  name        text not null,
  city        text,
  color       text not null default '#B8643F',
  since       int,
  tagline     text,
  description text,
  main_cat    text,
  instagram   text,
  whatsapp    text,
  status      text not null default 'pending' check (status in ('pending','approved','rejected','suspended')),
  commission  numeric(5,2) not null default 12 check (commission between 0 and 40),
  note        text,                                      -- nota del admin (motivo de rechazo/suspensión)
  created_at  timestamptz not null default now()
);
alter table public.profiles add constraint profiles_brand_fk foreign key (brand_id) references public.brands(id) on delete set null;

-- Datos privados de la marca (solo dueño y admin)
create table public.brand_private (
  brand_id  text primary key references public.brands(id) on delete cascade,
  rfc       text,
  clabe     text check (clabe is null or clabe ~ '^\d{18}$')
);

-- Categorías y subcategorías (auto-relación)
create table public.categories (
  id         text primary key,
  parent_id  text references public.categories(id) on delete cascade,
  name       text not null,
  sort       int not null default 0
);

-- Productos. Variantes (color|talla) y su stock en un mapa JSON para actualizar stock de forma atómica.
create table public.products (
  id            bigint primary key generated by default as identity,
  brand_id      text not null references public.brands(id) on delete cascade,
  name          text not null check (length(name) between 2 and 120),
  slug          text,
  cat           text not null references public.categories(id),
  sub           text not null references public.categories(id),
  shape         text,                                    -- ilustración si aún no hay fotos
  description   text not null,
  details       text,
  price         numeric(12,2) not null check (price > 0),
  compare_at    numeric(12,2) check (compare_at is null or compare_at > price),
  colors        text[] not null default '{}',
  sizes         text[] not null default '{}',
  stock         jsonb  not null default '{}'::jsonb,     -- {"hueso|M": 5, ...}
  specs         jsonb  not null default '{}'::jsonb,     -- {"Material": "Lino", ...}
  features      text[] not null default '{}',
  images        text[] not null default '{}',            -- URLs públicas de Supabase Storage
  weight        int check (weight is null or weight > 0),
  dims          text,
  status        text not null default 'pending_review' check (status in ('pending_review','active','paused','rejected')),
  reject_reason text,
  sales         int not null default 0,
  created_at    timestamptz not null default now(),
  published_at  timestamptz
);
create index products_brand_idx on public.products(brand_id);
create index products_status_idx on public.products(status);

-- Cupones (validados en el servidor por place_order)
create table public.coupons (
  code          text primary key,
  type          text not null check (type in ('percent','fixed','shipping')),
  value         numeric(12,2) not null default 0,
  min_subtotal  numeric(12,2),
  label         text,
  active        boolean not null default true
