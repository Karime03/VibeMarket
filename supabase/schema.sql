-- =====================================================================
--  VibeMarket — Esquema para Supabase (PostgreSQL 15+)
--  Cómo usarlo: Supabase → SQL Editor → New query → pega TODO → Run
--  Es re-ejecutable: borra y vuelve a crear las tablas de VibeMarket
--  (NO borra usuarios de Supabase Auth).
--
--  Contenido:
--    1. Tablas relacionales (perfiles, marcas, catálogo, pedidos, reseñas…)
--    2. Funciones auxiliares de rol (is_admin, my_brand…)
--    3. Trigger de registro: crea perfil (y marca si es vendedor)
--    4. Triggers de protección (un rol no puede cambiar campos de otro)
--    5. place_order(): registra el pedido validando precios y stock en el servidor
--    6. Row Level Security (RLS): qué puede ver/editar cada rol
--    7. Storage: bucket público para fotos de productos
--    8. Datos de configuración (categorías y cupones) — SIN productos de ejemplo
-- =====================================================================

-- ---------- 0. Reinicio (re-ejecutable) ----------
drop trigger if exists on_auth_user_created on auth.users;
drop table if exists public.newsletter_subscribers, public.contact_messages, public.saved_carts,
  public.addresses, public.wishlists, public.returns, public.review_votes, public.reviews,
  public.order_items, public.orders, public.products, public.coupons, public.categories,
  public.brand_private, public.brands, public.profiles cascade;
drop sequence if exists public.order_seq;

