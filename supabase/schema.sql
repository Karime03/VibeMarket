-- 2. FUNCIONES AUXILIARES (security definer: evitan recursión en RLS)
-- =====================================================================
create or replace function public.my_role() returns text
language sql stable security definer set search_path = public as $$
  select role from public.profiles where id = auth.uid() and status = 'active'
$$;
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(public.my_role() = 'admin', false)
$$;
create or replace function public.my_brand() returns text
language sql stable security definer set search_path = public as $$
  select brand_id from public.profiles where id = auth.uid() and role = 'vendor' and status = 'active'
$$;
create or replace function public.order_owner(oid text) returns uuid
language sql stable security definer set search_path = public as $$
  select user_id from public.orders where id = oid
$$;
create or replace function public.vendor_in_order(oid text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.order_items where order_id = oid and brand_id = public.my_brand())
$$;
create or replace function public.product_brand(pid bigint) returns text
language sql stable security definer set search_path = public as $$
  select brand_id from public.products where id = pid
$$;
-- Pantalla de acceso: ¿ya existe un administrador? (para la configuración inicial)
create or replace function public.admin_exists() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where role = 'admin')
$$;

-- =====================================================================
-- 3. REGISTRO: crea el perfil (y la marca si es vendedor)
-- =====================================================================
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  m   jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  r   text  := coalesce(m->>'role', 'buyer');
  b   jsonb := m->'brand';
  bid text;
begin
  if r not in ('buyer','vendor','admin') then r := 'buyer'; end if;
  -- Solo el PRIMER usuario puede registrarse como admin (configuración inicial)
  if r = 'admin' and exists (select 1 from public.profiles where role = 'admin') then r := 'buyer'; end if;
  if r = 'vendor' and (b is null or coalesce(b->>'name','') = '') then r := 'buyer'; end if;

  insert into public.profiles (id, role, name, email, phone, city, interests, prefs)
  values (new.id, r, coalesce(nullif(m->>'name',''), split_part(new.email,'@',1)), new.email,
          m->>'phone', m->>'city',
          coalesce(array(select jsonb_array_elements_text(coalesce(m->'interests','[]'::jsonb))), '{}'),
          coalesce(m->'prefs', '{}'::jsonb));

  if r = 'vendor' then
    perform set_config('vm.bypass', 'on', true);   -- permite enlazar la marca al perfil
    bid := lower(regexp_replace(coalesce(nullif(b->>'id',''), b->>'name'), '[^a-zA-Z0-9]+', '-', 'g'));
    bid := trim(both '-' from bid);
    if bid = '' or exists (select 1 from public.brands where id = bid) then
      bid := bid || '-' || substr(md5(random()::text), 1, 4);
    end if;
    insert into public.brands (id, owner_id, name, city, color, since, tagline, description, main_cat, instagram, whatsapp, status)
    values (bid, new.id, b->>'name', b->>'city', coalesce(b->>'color','#B8643F'),
            nullif(b->>'since','')::int, b->>'tagline', b->>'desc', b->>'mainCat', b->>'instagram', b->>'whatsapp', 'pending');
    insert into public.brand_private (brand_id, rfc, clabe) values (bid, nullif(upper(b->>'rfc'),''), nullif(b->>'clabe',''));
    update public.profiles set brand_id = bid where id = new.id;
  end if;
  return new;
end $$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- =====================================================================
-- 4. TRIGGERS DE PROTECCIÓN (además de RLS)
--    vm.bypass se activa solo dentro de funciones del servidor (place_order, vote_review)
-- =====================================================================
create or replace function public.bypass() returns boolean language sql stable as $$
  select coalesce(current_setting('vm.bypass', true), '') = 'on'
$$;

-- Perfiles: nadie salvo el admin cambia rol, estado, marca o correo
create or replace function public.profiles_guard() returns trigger language plpgsql as $$
begin
  if public.bypass() or public.is_admin() then return new; end if;
  new.role := old.role; new.status := old.status; new.brand_id := old.brand_id; new.email := old.email;
  return new;
end $$;
create trigger profiles_guard before update on public.profiles for each row execute function public.profiles_guard();

-- Marcas: el vendedor edita su perfil, pero no su estado ni su comisión
create or replace function public.brands_guard() returns trigger language plpgsql as $$
begin
  if public.bypass() or public.is_admin() then return new; end if;
  new.id := old.id; new.owner_id := old.owner_id; new.name := old.name;
  new.status := old.status; new.commission := old.commission; new.note := old.note;
  return new;
end $$;
create trigger brands_guard before update on public.brands for each row execute function public.brands_guard();

-- Productos: el vendedor no puede autopublicarse; solo el admin aprueba
create or replace function public.products_guard() returns trigger language plpgsql as $$
begin
  if public.bypass() then return new; end if;
  if public.is_admin() then
    if new.status = 'active' and (tg_op = 'INSERT' or old.status <> 'active') and new.published_at is null then
      new.published_at := now();
    end if;
    return new;
  end if;
  if tg_op = 'INSERT' then
    new.status := 'pending_review'; new.sales := 0; new.published_at := null; new.reject_reason := null;
    new.created_at := now();
    return new;
  end if;
  new.brand_id := old.brand_id; new.sales := old.sales; new.published_at := old.published_at; new.created_at := old.created_at;
  if new.status is distinct from old.status and not (
       (old.status = 'active'   and new.status = 'paused') or
       (old.status = 'paused'   and new.status = 'active') or
       (old.status = 'rejected' and new.status = 'pending_review')) then
    new.status := old.status;
  end if;
  if old.status = 'rejected' and new.status = 'pending_review' then new.reject_reason := null;
  else new.reject_reason := old.reject_reason; end if;
  return new;
end $$;
create trigger products_guard before insert or update on public.products for each row execute function public.products_guard();

-- Reseñas: el servidor fija autor, "compra verificada" y contadores
create or replace function public.reviews_guard() returns trigger language plpgsql as $$
begin
  if public.bypass() then return new; end if;
  if tg_op = 'INSERT' then
    new.user_id := auth.uid(); new.helpful := 0; new.status := 'published'; new.reply := null; new.created_at := now();
    new.verified := exists (
      select 1 from public.order_items i join public.orders o on o.id = i.order_id
      where o.user_id = auth.uid() and i.product_id = new.product_id and o.status in ('paid','preparing','shipped','delivered'));
    return new;
  end if;
  if public.is_admin() then return new; end if;
  -- la marca solo puede responder
  new.product_id := old.product_id; new.user_id := old.user_id; new.name := old.name; new.rating := old.rating;
  new.title := old.title; new.body := old.body; new.verified := old.verified; new.helpful := old.helpful; new.status := old.status;
  return new;
end $$;
create trigger reviews_guard before insert or update on public.reviews for each row execute function public.reviews_guard();

-- Pedidos: la marca solo actualiza estado/envío/historial; nunca montos, pago ni dirección
create or replace function public.orders_guard() returns trigger language plpgsql as $$
begin
  if public.bypass() or public.is_admin() then return new; end if;
  new.user_id := old.user_id; new.email := old.email; new.phone := old.phone; new.guest := old.guest;
  new.payment := old.payment; new.subtotal := old.subtotal; new.discount := old.discount;
  new.shipping_cost := old.shipping_cost; new.total := old.total; new.iva := old.iva; new.coupon := old.coupon;
  new.address := old.address; new.pay_ref := old.pay_ref; new.pay_expires := old.pay_expires; new.created_at := old.created_at;
  if new.status not in ('preparing','shipped','delivered') then new.status := old.status; end if;
  return new;
end $$;
create trigger orders_guard before update on public.orders for each row execute function public.orders_guard();

-- Devoluciones: el comprador solo solicita; la marca confirma recepción; el admin decide
create or replace function public.returns_guard() returns trigger language plpgsql as $$
begin
  if tg_op = 'INSERT' then
    if public.is_admin() then return new; end if;
    new.user_id := auth.uid(); new.status := 'requested'; new.admin_note := null; new.created_at := now();
    new.email := (select email from public.profiles where id = auth.uid());
    new.brand_id := public.product_brand(new.product_id);
    -- el monto sale del pedido real, no del navegador
    new.amount := coalesce((select i.price * least(new.qty, i.qty) from public.order_items i
                            where i.order_id = new.order_id and i.product_id = new.product_id limit 1), 0);
    return new;
  end if;
  if public.is_admin() then return new; end if;
  if not (old.status = 'approved' and new.status = 'received') then new.status := old.status; end if;
  new.admin_note := old.admin_note; new.amount := old.amount;
  return new;
end $$;
create trigger returns_guard before insert or update on public.returns for each row execute function public.returns_guard();

-- =====================================================================
-- 5. REGISTRO DEL PEDIDO (checkout simulado)
--    Recalcula precios, cupón y stock en el servidor, descuenta inventario
--    y guarda el pago simulado. El navegador NO decide montos.
-- =====================================================================
create or replace function public.place_order(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  it       jsonb;
  prod     public.products%rowtype;
  k        text;
  q        int;
  avail    int;
  sub      numeric(12,2) := 0;
  disc     numeric(12,2) := 0;
  ship     numeric(12,2) := greatest(coalesce((p->>'shipping_cost')::numeric, 0), 0);
  tot      numeric(12,2);
  cp       public.coupons%rowtype;
  uid      uuid := auth.uid();
  mail     text;
  pay      jsonb := coalesce(p->'payment', '{}'::jsonb);
  method   text := coalesce(pay->>'method', '');
  st       text;
  oid      text;
  vstat    jsonb := '{}'::jsonb;
  hist     jsonb;
  ref      text;
  exp      timestamptz;
begin
  perform set_config('vm.bypass', 'on', true);

  if jsonb_array_length(coalesce(p->'items', '[]'::jsonb)) = 0 then raise exception 'El carrito está vacío'; end if;
  if method not in ('card','paypal','mercadopago','oxxo') then raise exception 'Método de pago no válido'; end if;
  if method <> 'oxxo' and coalesce(pay->>'status','') <> 'approved' then raise exception 'El pago no fue autorizado'; end if;
  if coalesce(p->'address'->>'cp','') !~ '^\d{5}$' then raise exception 'Código postal inválido'; end if;

  if uid is not null then
    select email into mail from public.profiles where id = uid and status = 'active';
    if mail is null then raise exception 'Cuenta no válida o suspendida'; end if;
    if (select role from public.profiles where id = uid) <> 'buyer' then raise exception 'Solo las cuentas de comprador pueden comprar'; end if;
  else
    mail := lower(trim(p->>'email'));
    if mail !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Correo inválido'; end if;
  end if;

  -- 1) Validar productos, precios reales y stock (bloqueando filas)
  for it in select * from jsonb_array_elements(p->'items') loop
    select * into prod from public.products where id = (it->>'id')::bigint for update;
    if not found or prod.status <> 'active'
       or (select status from public.brands where id = prod.brand_id) <> 'approved' then
      raise exception 'Un producto ya no está disponible';
    end if;
    k := (it->>'color') || '|' || (it->>'size');
    q := (it->>'qty')::int;
    avail := coalesce((prod.stock->>k)::int, 0);
    if q is null or q < 1 or q > avail then
      raise exception 'Stock insuficiente de "%" (%): quedan %', prod.name, replace(k, '|', ' / '), avail;
    end if;
    sub := sub + prod.price * q;
  end loop;

  -- 2) Cupón (reglas del servidor)
  if coalesce(p->>'coupon','') <> '' then
    select * into cp from public.coupons where code = upper(p->>'coupon') and active;
    if found and (cp.min_subtotal is null or sub >= cp.min_subtotal) then
      if cp.type = 'percent' then disc := round(sub * cp.value / 100, 2);
      elsif cp.type = 'fixed' then disc := least(cp.value, sub);
      elsif cp.type = 'shipping' then ship := 0; end if;
    else cp := null; end if;
  end if;
  tot := sub - disc + ship;

  -- 3) Estado según el pago simulado
  if method = 'oxxo' then
    st := 'pending_payment';
    ref := '9300 ' || lpad((floor(random()*10000))::text, 4, '0') || ' ' || lpad((floor(random()*10000))::text, 4, '0');
    exp := now() + interval '72 hours';
  else st := 'paid'; end if;

  hist := jsonb_build_array(jsonb_build_object('status','received','title','Pedido recibido',
            'detail', jsonb_array_length(p->'items') || ' producto(s) · $' || to_char(tot, 'FM999,999,990.00') || ' MXN', 'date', now()));
  hist := hist || case when st = 'paid'
    then jsonb_build_array(jsonb_build_object('status','paid','title','Pago aprobado (simulado)','detail', coalesce(pay->>'label', method), 'date', now()))
    else jsonb_build_array(jsonb_build_object('status','pending_payment','title','Esperando pago en OXXO','detail','Referencia ' || ref, 'date', now())) end;

  insert into public.orders (user_id, email, phone, guest, status, payment, subtotal, discount, shipping_cost, total, iva,
                             coupon, shipping, address, history, pay_ref, pay_expires)
  values (uid, mail, p->>'phone', uid is null, st,
          jsonb_build_object('method', method, 'label', pay->>'label', 'status', case when st = 'paid' then 'approved' else 'pending' end,
                             'last4', pay->>'last4', 'card_brand', pay->>'card_brand', 'installments', pay->>'installments',
                             'auth_code', case when st = 'paid' then upper(substr(md5(random()::text), 1, 8)) end, 'simulated', true),
          sub, disc, ship, tot, round(tot - tot / 1.16, 2), cp.code,
          jsonb_build_object('method', p->'shipping'->>'method', 'carrier', p->'shipping'->>'carrier', 'eta', p->'shipping'->>'eta', 'tracking', null),
          p->'address', hist, ref, exp)
  returning id into oid;

  -- 4) Partidas del pedido + descuento de inventario + ventas
  for it in select * from jsonb_array_elements(p->'items') loop
    select * into prod from public.products where id = (it->>'id')::bigint;
    k := (it->>'color') || '|' || (it->>'size');
    q := (it->>'qty')::int;
    insert into public.order_items (order_id, product_id, brand_id, name, color, size, qty, price)
    values (oid, prod.id, prod.brand_id, prod.name, it->>'color', it->>'size', q, prod.price);
    update public.products
       set stock = jsonb_set(stock, array[k], to_jsonb(coalesce((stock->>k)::int, 0) - q)), sales = sales + q
     where id = prod.id;
    vstat := vstat || jsonb_build_object(prod.brand_id, 'pending');
  end loop;
  update public.orders set vendor_status = vstat where id = oid;

  -- 5) Guardar la dirección si el comprador aún no tiene ninguna
  if uid is not null and not exists (select 1 from public.addresses where user_id = uid) then
    insert into public.addresses (user_id, position, label, fname, lname, street, colonia, cp, city, state)
    values (uid, 0, 'Casa', p->'address'->>'fname', p->'address'->>'lname', p->'address'->>'street',
            p->'address'->>'colonia', p->'address'->>'cp', p->'address'->>'city', p->'address'->>'state');
  end if;

  return (select to_jsonb(o) || jsonb_build_object('items',
            (select jsonb_agg(to_jsonb(i) order by i.id) from public.order_items i where i.order_id = oid))
          from public.orders o where o.id = oid);
end $$;

-- Voto "útil" en una reseña (uno por usuario)
create or replace function public.vote_review(rid bigint) returns int
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  if auth.uid() is null then raise exception 'Inicia sesión para votar'; end if;
  perform set_config('vm.bypass', 'on', true);
  insert into public.review_votes (review_id, user_id) values (rid, auth.uid()) on conflict do nothing;
  if found then update public.reviews set helpful = helpful + 1 where id = rid; end if;
  select helpful into n from public.reviews where id = rid;
  return n;
end $$;

-- Suscripción al newsletter (sin exponer la lista)
create or replace function public.subscribe_newsletter(p_email text, p_interests text[]) returns void
language sql security definer set search_path = public as $$
  insert into public.newsletter_subscribers (email, interests) values (lower(trim(p_email)), coalesce(p_interests, '{}'))
  on conflict (email) do update set interests = excluded.interests
$$;

