  user_id         uuid references public.profiles(id) on delete set null,   -- null = invitado
  email           text not null,
  phone           text,
  guest           boolean not null default false,
  status          text not null default 'pending_payment'
                  check (status in ('pending_payment','paid','preparing','shipped','delivered','cancelled','refunded')),
  payment         jsonb not null default '{}'::jsonb,   -- {method, label, status, last4, card_brand, auth_code, simulated}
  subtotal        numeric(12,2) not null,
  discount        numeric(12,2) not null default 0,
  shipping_cost   numeric(12,2) not null default 0,
  total           numeric(12,2) not null,
  iva             numeric(12,2) not null default 0,
  coupon          text references public.coupons(code) on delete set null,
  shipping        jsonb not null default '{}'::jsonb,   -- {method, carrier, eta, tracking}
